import readline from "readline/promises";
import { stdin as input, stdout as output } from "process";
import { TOOL_DECLARATIONS, TOOL_HANDLERS } from "./tools.mjs";

// Terminal colors
const C = {
  reset: "\x1b[0m",
  bold: "\x1b[1m",
  green: "\x1b[32m",
  cyan: "\x1b[36m",
  yellow: "\x1b[33m",
  red: "\x1b[31m",
  dim: "\x1b[2m",
};

const DEFAULT_MODELS = [
  "gemini-3.1-flash-lite",
  "gemini-3.8-flash",
  "gemini-flash-latest",
];
const API_BASE = "https://generativelanguage.googleapis.com/v1beta/models";

class AIAgent {
  constructor(apiKey) {
    this.apiKey = apiKey;
    this.history = [];
    this.activeModel = DEFAULT_MODELS[0];
    this.systemInstruction = {
      parts: [
        {
          text: `You are an interactive Cybersecurity Education & Penetration Testing Tutor Bot.
Your mission is to teach the user ethical hacking, offensive security theory, defensive countermeasures, and secure application development for authorized lab training (e.g., OWASP Juice Shop, DVWA, WebGoat, TryHackMe, PortSwigger Academy).

Teaching Methodology:
1. Explain Vulnerability Mechanics: Break down how security flaws (such as OWASP Top 10, Command Injection, SQL Injection, XSS, SSRF, IDOR, Authentication Bypasses) occur at the architectural and code levels.
2. Abstract Code Comparison: Present simplified, abstract code snippets contrasting vulnerable patterns with secure, hardened code (e.g., using parameterized APIs, allowlisting, input validation, defense-in-depth).
3. Penetration Testing Frameworks: Teach standardized assessment methodology (PTES, OWASP WSTG, NIST SP 800-115) across Reconnaissance, Threat Modeling, Vulnerability Analysis, Exploitation Theory, and Reporting.
4. Remediation & Defense First: Always provide robust defensive mitigations, patch examples, and security best practices alongside concepts.
5. Interactive Learning: Offer step-by-step learning modules, quizzes, and safe lab scenario suggestions to help the user master practical cybersecurity concepts.
6. Tools: Use your tools (searchWeb, calculate, writeFile, readFile, listFiles, getCurrentTime) to look up security references, CVE databases, write study guides, or format lesson notes.`,
        },
      ],
    };
  }

  async callGemini(contents) {
    let lastError = null;

    for (const model of DEFAULT_MODELS) {
      const url = `${API_BASE}/${model}:generateContent?key=${this.apiKey}`;
      const payload = {
        systemInstruction: this.systemInstruction,
        contents,
        tools: [{ functionDeclarations: TOOL_DECLARATIONS }],
        generationConfig: {
          temperature: 0.2,
        },
      };

      try {
        const res = await fetch(url, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify(payload),
        });

        if (res.ok) {
          this.activeModel = model;
          return await res.json();
        }

        const errText = await res.text();
        // If busy or deprecated, try next model
        if (res.status === 503 || res.status === 404) {
          lastError = new Error(`Model ${model} (${res.status}): ${errText}`);
          continue;
        }

        throw new Error(`Gemini API error (${res.status}): ${errText}`);
      } catch (err) {
        lastError = err;
      }
    }

    throw lastError || new Error("Failed to communicate with Gemini API models.");
  }

  async processUserMessage(userText) {
    // 1. Add user message to history
    this.history.push({
      role: "user",
      parts: [{ text: userText }],
    });

    const MAX_TOOL_STEPS = 5;
    let step = 0;

    while (step < MAX_TOOL_STEPS) {
      step++;
      const data = await this.callGemini(this.history);
      const candidate = data.candidates?.[0];

      if (!candidate || !candidate.content) {
        return "⚠️ No response generated by the model.";
      }

      const content = candidate.content;
      this.history.push(content);

      // Check for function calls
      const parts = content.parts || [];
      const functionCallPart = parts.find((p) => p.functionCall);

      if (functionCallPart && functionCallPart.functionCall) {
        const { name, args } = functionCallPart.functionCall;
        console.log(
          `  ${C.cyan}⚙️  [Tool Call]${C.reset} ${C.bold}${name}${C.reset}(${JSON.stringify(
            args || {}
          )})`
        );

        const handler = TOOL_HANDLERS[name];
        let toolOutput;
        if (handler) {
          try {
            toolOutput = await handler(args || {});
          } catch (err) {
            toolOutput = JSON.stringify({ error: err.message });
          }
        } else {
          toolOutput = JSON.stringify({ error: `Tool "${name}" is not implemented.` });
        }

        console.log(
          `  ${C.dim}↳ Output: ${toolOutput.slice(0, 120)}${
            toolOutput.length > 120 ? "..." : ""
          }${C.reset}`
        );

        // Feed tool response back into conversation
        this.history.push({
          role: "user",
          parts: [
            {
              functionResponse: {
                name,
                response: { output: toolOutput },
              },
            },
          ],
        });
        // Loop back to let model inspect tool output
        continue;
      }

      // If no function call, we have the final textual response
      const textPart = parts.find((p) => p.text);
      return textPart ? textPart.text : "Task complete.";
    }

    return "⚠️ Reached maximum autonomous tool execution steps.";
  }
}

async function runSelfTest() {
  console.log(`\n${C.cyan}${C.bold}🔍 Running Agent Self-Test (Zero API Key Mode)...${C.reset}\n`);

  try {
    // 1. Time tool
    process.stdout.write("  Testing getCurrentTime... ");
    const timeRes = await TOOL_HANDLERS.getCurrentTime();
    console.log(`${C.green}✓ OK${C.reset} (${JSON.parse(timeRes).localTime})`);

    // 2. Math tool
    process.stdout.write("  Testing calculate ('125 * 8 + 50')... ");
    const calcRes = await TOOL_HANDLERS.calculate({ expression: "125 * 8 + 50" });
    const parsedCalc = JSON.parse(calcRes);
    if (parsedCalc.result === "1050") {
      console.log(`${C.green}✓ OK${C.reset} (Result: 1050)`);
    } else {
      console.log(`${C.red}✗ Failed${C.reset}`);
    }

    // 3. File write tool
    process.stdout.write("  Testing writeFile ('test_agent.tmp')... ");
    await TOOL_HANDLERS.writeFile({
      filename: "test_agent.tmp",
      content: "AI Agent system check passed.",
    });
    console.log(`${C.green}✓ OK${C.reset}`);

    // 4. File read tool
    process.stdout.write("  Testing readFile ('test_agent.tmp')... ");
    const readRes = JSON.parse(await TOOL_HANDLERS.readFile({ filename: "test_agent.tmp" }));
    if (readRes.content.includes("passed")) {
      console.log(`${C.green}✓ OK${C.reset}`);
    }

    // 5. List files tool
    process.stdout.write("  Testing listFiles ('.')... ");
    const listRes = JSON.parse(await TOOL_HANDLERS.listFiles({ directory: "." }));
    console.log(`${C.green}✓ OK${C.reset} (${listRes.files.length} items found)`);

    // Clean up temporary test file
    await (await import("fs/promises")).unlink("test_agent.tmp").catch(() => {});

    console.log(`\n${C.green}${C.bold}🎉 All Agent tools are healthy and operational!${C.reset}\n`);
  } catch (err) {
    console.error(`\n${C.red}Self-test error: ${err.message}${C.reset}\n`);
  }
}

async function main() {
  // If user passes --test or -t
  if (process.argv.includes("--test") || process.argv.includes("-t")) {
    await runSelfTest();
    return;
  }
  console.log(`\n${C.green}${C.bold}==============================================${C.reset}`);
  console.log(`${C.green}${C.bold}   🛡️  Pentest & Cybersecurity Tutor Bot     ${C.reset}`);
  console.log(`${C.green}${C.bold}==============================================${C.reset}\n`);

  let apiKey = process.env.GEMINI_API_KEY;

  const rl = readline.createInterface({ input, output });

  if (!apiKey) {
    console.log(`${C.yellow}No GEMINI_API_KEY found in environment or .env file.${C.reset}`);
    console.log(`Get a free key (no credit card needed) at: https://aistudio.google.com\n`);
    apiKey = await rl.question(`${C.bold}Enter your free Gemini API key: ${C.reset}`);
    apiKey = apiKey.trim();
    if (!apiKey) {
      console.log(`${C.red}Error: API key is required to run the agent.${C.reset}`);
      rl.close();
      return;
    }
  }

  const agent = new AIAgent(apiKey);

  // Check if a single query was passed via command line (e.g. node agent.mjs "What time is it?")
  const queryArgs = process.argv.slice(2).filter((arg) => !arg.startsWith("-"));
  if (queryArgs.length > 0) {
    const singlePrompt = queryArgs.join(" ");
    console.log(`${C.bold}Query:${C.reset} ${singlePrompt}`);
    console.log(`${C.dim}Using model: ${agent.activeModel}...${C.reset}`);
    const response = await agent.processUserMessage(singlePrompt);
    console.log(`\n${C.green}${C.bold}Agent:${C.reset} ${response}\n`);
    rl.close();
    return;
  }

  console.log(`\n${C.green}✓ Agent online and ready! (Model: ${agent.activeModel})${C.reset}`);
  console.log(`${C.dim}Available tools: searchWeb, calculate, writeFile, readFile, listFiles, getCurrentTime${C.reset}`);
  console.log(`${C.dim}Type 'exit' or 'quit' to close.${C.reset}\n`);

  while (true) {
    const prompt = await rl.question(`${C.bold}You: ${C.reset}`);
    const trimmed = prompt.trim();

    if (!trimmed) continue;
    if (["exit", "quit", "q"].includes(trimmed.toLowerCase())) {
      console.log(`\n${C.yellow}Goodbye! 👋${C.reset}\n`);
      break;
    }

    try {
      process.stdout.write(`${C.dim}Thinking...${C.reset}\r`);
      const response = await agent.processUserMessage(trimmed);
      console.log(`\r${" ".repeat(20)}\r${C.green}${C.bold}Agent:${C.reset} ${response}\n`);
    } catch (err) {
      console.error(`\n${C.red}Error: ${err.message}${C.reset}\n`);
    }
  }

  rl.close();
}

main().catch((err) => {
  console.error("Fatal error:", err);
});

